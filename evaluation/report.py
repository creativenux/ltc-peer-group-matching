def _cell(value, column: str):
    """Round for readability: p-values to 3 significant figures, other numbers to 4 dp."""
    if not isinstance(value, float):
        return value
    if math.isnan(value):
        return ""
    return f"{value:.3g}" if column.endswith(" p") else round(value, 4)


def _write(path: Path, header: list, rows: list) -> Path:
    # utf-8-sig so the files open correctly in Excel
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows([[_cell(v, header[i]) for i, v in enumerate(r)] for r in rows])
    return path


def write_csv_tables(results: dict, outdir) -> list:
    """Write every table in the report as its own CSV file; returns the paths."""
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    stem = f"evaluation_n{results['n']}"
    methods, s = results["methods"], results["summary"]
    files = []

    header = ["Method"] + [f"{METRICS[k][0]} {part}" for k in METRICS for part in ("mean", "sd")]
    rows = [[METHOD_LABELS[m]] + [v for k in METRICS for v in (s[k][m]["mean"], s[k][m]["sd"])] for m in methods]
    files.append(_write(outdir / f"{stem}_metrics.csv", header, rows))

    within = results["within_group_dissimilarity"]
    header = ["Attribute"] + [METHOD_LABELS[m] for m in methods]
    rows = [[ATTRIBUTES[a]["label"]] + [within[m][a] for m in methods] for a in HOMOGENEITY_ATTRIBUTES]
    files.append(_write(outdir / f"{stem}_attribute_dissimilarity.csv", header, rows))

    header = ["Metric", "Friedman chi-square", "Friedman p", "Kendall's W", "Baseline",
              "Median difference", "Wilcoxon p", "Holm-adjusted p", "Rank-biserial r", "Effect size",
              "Interpretation"]
    rows = []
    for k, (label, _) in METRICS.items():
        t = results["tests"][k]
        fr = t["friedman"]
        base = [label] + ([fr["statistic"], fr["p_value"], fr["kendalls_w"]] if fr else ["", "", ""])
        if not t["pairwise"]:
            rows.append(base + ["", "", "", "", "", "", t["note"] or fr["interpretation"]])
        for p in t["pairwise"]:
            text = p["interpretation"]
            for key in sorted(METHOD_LABELS, key=len, reverse=True):  # longest first: "unweighted_gower" before "weighted_gower"
                text = text.replace(key, METHOD_LABELS[key])
            rows.append(base + [METHOD_LABELS[p["baseline"]], p["median_difference"], p["p_value"],
                                p["p_holm"], p["rank_biserial"], p["effect_size"], text])
    files.append(_write(outdir / f"{stem}_statistical_tests.csv", header, rows))

    sens = results["sensitivity"]
    wgd = {(p["attribute"], p["direction"]): p["within_group_distance"] for p in sens["perturbations"]}
    header = ["Rank", "Attribute", "Weight", "ARI (+10%)", "ARI (-10%)", "Mean change",
              "Within-group distance (+10%)", "Within-group distance (-10%)"]
    rows = [[i + 1, ATTRIBUTES[x["attribute"]]["label"], x["original_weight"], x["ari_plus"], x["ari_minus"],
             x["mean_change"], wgd[(x["attribute"], "+10%")], wgd[(x["attribute"], "-10%")]]
            for i, x in enumerate(sens["ranking"])]
    rows.append(["", "Reference: seed change only", "", sens["seed_reference_ari"], "", "",
                 sens["seed_reference_within_group_distance"], ""])
    rows.append(["", "Reference: original grouping", "", "", "", "", sens["base_within_group_distance"], ""])
    files.append(_write(outdir / f"{stem}_sensitivity.csv", header, rows))

    header = ["Seed", "Method"] + [METRICS[k][0] for k in METRICS]
    rows = [[r["seed"], METHOD_LABELS[m]] + [r["metrics"][m][k] for k in METRICS]
            for r in results["replicates"] for m in methods]
    files.append(_write(outdir / f"{stem}_replicates.csv", header, rows))
    return files
