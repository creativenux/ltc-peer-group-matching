"""
report.py

Writes the evaluation results as a markdown report and as CSV tables. All
numbers, including those in the summary paragraphs, come from the results
dictionary, so the text always matches the tables.
"""

from __future__ import annotations

import csv
import math
from datetime import datetime, timezone
from pathlib import Path

from matching.attributes import ATTRIBUTES, HOMOGENEITY_ATTRIBUTES

REFERENCE = "weighted_gower"

METHOD_LABELS = {
    "weighted_gower": "Weighted Gower (full method)",
    "unweighted_gower": "Unweighted Gower",
    "single_age_band": "Single attribute: age band",
    "single_primary_support_goal": "Single attribute: support goal",
    "random": "Random",
}

# metric -> (label, higher is better)
METRICS = {
    "silhouette_weighted": ("Silhouette (weighted Gower matrix)", True),
    "silhouette_unweighted": ("Silhouette (unweighted Gower matrix)", True),
    "within_group_distance": ("Within-group weighted Gower distance", False),
    "cohesion_index": ("Cohesion index (mean Score(G))", True),
    "unmatched_rate": ("Unmatched rate", False),
}

PRIMARY_BASELINES = ["random", "single_age_band", "single_primary_support_goal"]


def _fmt(x, digits=4) -> str:
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{digits}f}"


def _p(p) -> str:
    return "< 0.001" if p < 0.001 else f"{p:.3f}"


def _table(header, rows) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _significantly_better(tests, metric, baseline) -> bool:
    for row in (tests.get(metric) or {}).get("pairwise", []):
        if row["baseline"] == baseline:
            return row["p_holm"] < 0.05 and row["interpretation"].startswith(f"{REFERENCE} is better")
    return False


def _setup(r) -> str:
    return "\n".join([
        "## Setup",
        "",
        f"- Replicate datasets: {len(r['seeds'])} (seeds {r['seeds'][0]} to {r['seeds'][-1]}), "
        f"n = {r['n']:,} profiles each, generated by `dataset_generation/generate_dataset.py`.",
        "- Every method runs on the same eligible pools (shared condition category and language) "
        "with the same group-size plan (6 to 8), so group size never differs between methods.",
        f"- Methods: {', '.join(METHOD_LABELS[m] for m in r['methods'])}.",
        f"- Total runtime: {r['runtime_seconds'] / 60:.1f} minutes.",
    ])


def _metrics_section(r) -> str:
    s = r["summary"]
    rows = [[METHOD_LABELS[m]] + [f"{_fmt(s[k][m]['mean'])} ({_fmt(s[k][m]['sd'])})" for k in METRICS]
            for m in r["methods"]]
    header = ["Method"] + [METRICS[k][0] for k in METRICS]

    attr = r["within_group_dissimilarity"]
    attr_rows = [[ATTRIBUTES[a]["label"]] + [_fmt(attr[m][a], 3) for m in r["methods"]]
                 for a in HOMOGENEITY_ATTRIBUTES]

    sw = s["silhouette_weighted"]
    su = s["silhouette_unweighted"]
    ci = s["cohesion_index"]
    para = (
        f"Across {len(r['seeds'])} replicate datasets of {r['n']:,} synthetic profiles, the weighted "
        f"Gower method produced a mean silhouette of {_fmt(sw[REFERENCE]['mean'], 3)} on the weighted "
        f"Gower matrix, against {_fmt(sw['random']['mean'], 3)} for random assignment, "
        f"{_fmt(sw['single_age_band']['mean'], 3)} for age-band matching and "
        f"{_fmt(sw['single_primary_support_goal']['mean'], 3)} for support-goal matching. "
        f"On the unweighted matrix the corresponding values were {_fmt(su[REFERENCE]['mean'], 3)}, "
        f"{_fmt(su['random']['mean'], 3)}, {_fmt(su['single_age_band']['mean'], 3)} and "
        f"{_fmt(su['single_primary_support_goal']['mean'], 3)}. The mean cohesion index was "
        f"{_fmt(ci[REFERENCE]['mean'], 3)} for the weighted method and {_fmt(ci['random']['mean'], 3)} "
        f"for random assignment. The unmatched rate was identical for every method "
        f"({_fmt(s['unmatched_rate'][REFERENCE]['mean'] * 100, 1)}%), because all methods share "
        f"the same pools and group-size plan. Silhouette values are low in absolute terms because "
        f"each pool is divided into many groups of six to eight drawn from people who share many "
        f"attribute values, so neighbouring groups are similar; the comparison between methods is "
        f"what the metric is used for here."
    )
    return "\n".join([
        "## 1. Cohesion metrics",
        "",
        "Mean (standard deviation) across replicates. Higher silhouette and cohesion index are more "
        "cohesive; lower within-group distance is more cohesive. Silhouette is an established "
        "measure (Rousseeuw, 1987); the cohesion index is specific to this project. The weighted "
        "method optimises the weighted Gower matrix, so the unweighted silhouette is reported as a "
        "check that its advantage does not depend only on being scored on its own distance.",
        "",
        _table(header, rows),
        "",
        "Mean within-group dissimilarity per homogeneity attribute (0 = every group member shares "
        "the value; lower is more cohesive):",
        "",
        _table(["Attribute"] + [METHOD_LABELS[m] for m in r["methods"]], attr_rows),
        "",
        "### For the dissertation",
        "",
        para,
    ])


def _tests_section(r) -> str:
    t = r["tests"]
    out = ["## 2. Statistical tests", "",
           "Friedman test across all five methods for each metric, with Kendall's W as effect size. "
           "Where it is significant, Wilcoxon signed-rank tests compare the weighted Gower method "
           "with each baseline, Holm-Bonferroni corrected, with the matched-pairs rank-biserial "
           "correlation r as effect size (|r| < 0.1 negligible, < 0.3 small, < 0.5 medium, "
           "otherwise large).", ""]
    for metric, (label, _) in METRICS.items():
        res = t[metric]
        out.append(f"**{label}.** ")
        if res["friedman"] is None:
            out[-1] += res["note"]
            out.append("")
            continue
        out[-1] += res["friedman"]["interpretation"]
        if res["note"]:
            out[-1] += " " + res["note"]
        out.append("")
        if res["pairwise"]:
            out.append(_table(
                ["Baseline", "Median difference", "Holm-adjusted p", "Rank-biserial r", "Effect"],
                [[METHOD_LABELS[p["baseline"]], f"{p['median_difference']:+.4f}", _p(p["p_holm"]),
                  f"{p['rank_biserial']:.2f}", p["effect_size"]] for p in res["pairwise"]]))
            out.append("")

    primary = [b for b in PRIMARY_BASELINES if _significantly_better(t, "silhouette_weighted", b)]
    check = [b for b in PRIMARY_BASELINES if _significantly_better(t, "silhouette_unweighted", b)]
    supported = len(primary) == len(PRIMARY_BASELINES)
    s = r["summary"]
    within = r["within_group_dissimilarity"]
    tighter_w = [a for a in HOMOGENEITY_ATTRIBUTES
                 if within[REFERENCE][a] < within["unweighted_gower"][a]]
    tighter_u = [a for a in HOMOGENEITY_ATTRIBUTES
                 if within["unweighted_gower"][a] < within[REFERENCE][a]]

    def _pairs(attrs, first, second):
        return ", ".join(f"{ATTRIBUTES[a]['label']} {within[first][a]:.3f} vs "
                         f"{within[second][a]:.3f}" for a in attrs)

    para = (
        f"The hypothesis is {'supported' if supported else 'not supported'} on the primary metric: "
        f"the weighted method's silhouette on the weighted Gower matrix was significantly higher "
        f"than {len(primary)} of the {len(PRIMARY_BASELINES)} baselines named in the hypothesis "
        f"(random assignment and both single-attribute methods) after Holm correction. On the "
        f"unweighted matrix, which the weighted method does not optimise, it was significantly "
        f"higher than {len(check)} of the {len(PRIMARY_BASELINES)}, so the advantage does not "
        f"depend on the distance used to measure it. The comparison with unweighted Gower is "
        f"different: each Gower variant achieved the higher silhouette on the distance it "
        f"optimises (weighted {_fmt(s['silhouette_weighted'][REFERENCE]['mean'], 3)} vs "
        f"{_fmt(s['silhouette_weighted']['unweighted_gower']['mean'], 3)} on the weighted matrix; "
        f"unweighted {_fmt(s['silhouette_unweighted']['unweighted_gower']['mean'], 3)} vs "
        f"{_fmt(s['silhouette_unweighted'][REFERENCE]['mean'], 3)} on the unweighted matrix), so "
        f"silhouette cannot rank the two. What the weights change is what group members share: "
        f"within-group dissimilarity was lower under the weighted method for "
        f"{_pairs(tighter_w, REFERENCE, 'unweighted_gower')}, and lower under the unweighted "
        f"method for {_pairs(tighter_u, 'unweighted_gower', REFERENCE)}."
    )
    out += ["### For the dissertation", "", para]
    return "\n".join(out)


def _sensitivity_section(r) -> str:
    sens = r["sensitivity"]
    ranking = sens["ranking"]
    wgd = {(p["attribute"], p["direction"]): p["within_group_distance"]
           for p in sens["perturbations"]}
    rows = [[i + 1, ATTRIBUTES[x["attribute"]]["label"], f"{x['original_weight']:.4f}",
             _fmt(x["ari_plus"], 3), _fmt(x["ari_minus"], 3), _fmt(x["mean_change"], 3),
             _fmt(wgd[(x["attribute"], "+10%")], 4), _fmt(wgd[(x["attribute"], "-10%")], 4)]
            for i, x in enumerate(ranking)]
    aris = [a for x in ranking for a in (x["ari_plus"], x["ari_minus"])]
    ref = sens["seed_reference_ari"]
    distances = list(wgd.values())
    least_two = ranking[-2:]
    rest = ranking[:-2]
    spread = rest[0]["mean_change"] - rest[-1]["mean_change"]
    random_wgd = r["summary"]["within_group_distance"]["random"]["mean"]
    para = (
        f"Each of the eight weights was changed by plus and minus 10% (with the others rescaled to "
        f"sum to 1) and the weighted method re-run on the same dataset (seed {sens['seed']}). "
        f"Every change altered a substantial share of group memberships (ARI {min(aris):.3f} to "
        f"{max(aris):.3f}), comparable to re-running the unchanged method with a different random "
        f"seed (ARI {ref:.3f}). This reflects many near-equivalent groupings: many profiles share "
        f"the same attribute values, so different memberships can be equally cohesive. Group "
        f"quality was stable: the mean within-group distance, measured under the original weights, "
        f"ranged from {min(distances):.4f} to {max(distances):.4f} across the perturbations, "
        f"against {sens['base_within_group_distance']:.4f} for the original grouping, "
        f"{sens['seed_reference_within_group_distance']:.4f} for the different seed and "
        f"{random_wgd:.4f} for random assignment (mean across replicates). Changes to the "
        f"{ATTRIBUTES[least_two[1]['attribute']]['label']} and "
        f"{ATTRIBUTES[least_two[0]['attribute']]['label']} weights disturbed membership least "
        f"(mean change {least_two[1]['mean_change']:.3f} and {least_two[0]['mean_change']:.3f}); "
        f"the other six differ from one another by at most {spread:.3f}, too little to rank them."
    )
    return "\n".join([
        "## 3. Weight sensitivity",
        "",
        "Adjusted Rand Index (Hubert & Arabie, 1985) between the original grouping and the grouping "
        "after each weight change; 1 means identical groupings. Ranked by mean change "
        "(1 − mean ARI of the two directions). Within-group distance is measured under the "
        "original weights for every grouping, so it shows whether group quality holds when "
        "membership changes. ARI is an evaluation measure only.",
        "",
        _table(["Rank", "Attribute", "Weight", "ARI (+10%)", "ARI (−10%)", "Mean change",
                "Within-group distance (+10%)", "Within-group distance (−10%)"], rows),
        "",
        f"Reference: the original grouping has within-group distance "
        f"{sens['base_within_group_distance']:.4f}. Re-running with only the random seed changed "
        f"gives ARI = {ref:.3f} and within-group distance "
        f"{sens['seed_reference_within_group_distance']:.4f}.",
        "",
        "### For the dissertation",
        "",
        para,
    ])


LIMITATIONS = """## Limitations

- The support goal, support orientation, engagement level and isolation score are synthetic, based on stated assumptions rather than population data. The results show how the method behaves on data built to those assumptions, not how real groups would form.
- The evaluation measures group similarity only. Whether cohesive groups improve wellbeing or reduce loneliness is outside the scope of this project.
- The weights are derived from the literature, not fitted to outcome data; section 3 tests how far the groupings depend on them.
- The cohesion index is specific to this project and not externally validated. Silhouette is the established measure.
- Silhouette on the weighted Gower matrix favours the weighted method, because that method optimises this distance; the unweighted silhouette is reported as a check.
- The shared-language rule leaves people in very small language pools unmatched; the unmatched rate reports this."""


def build_report(results: dict) -> str:
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return "\n\n".join([
        "# Matching Evaluation Report",
        f"Generated {ts}.",
        _setup(results),
        _metrics_section(results),
        _tests_section(results),
        _sensitivity_section(results),
        LIMITATIONS,
    ]) + "\n"


